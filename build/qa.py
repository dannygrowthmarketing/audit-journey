  ('What are AEO and GEO, and do they matter for a salon?',
   'They are about being the answer when someone asks Google\'s AI, ChatGPT or Gemini for a salon. It matters more each month. Clear prices, consistent details, schema and FAQ pages are what get you quoted.'),
  ('What content should we post?',
   'Before/afters with the stylist\'s name, stylist spotlights, weekend slots, and client reels with consent. People book a person, not "our professionals".'),
